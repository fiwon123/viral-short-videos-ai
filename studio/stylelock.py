"""Channel style lock: the approved look and rules, enforced by the studio itself.

Different assistants (or people) working on one channel drift: one generates new
characters, another adds a narrator, a third changes the grade. The style lock
stops that at the tool level instead of relying on whoever is working to remember.

``<channel>/style-lock.json`` (next to ``channel.json``) records what the user
approved: the cast rigs, whether characters speak, runtime and format, allowed
grades, music, the sound library, paths that must never be used, free-text
rules, reference episodes and a versioned changelog. With ``"enforce": true``
``validate``, ``audio``, ``check-visual``, ``still`` and ``render`` refuse an
episode that breaks it. Episodes made before the lock are listed under ``exempt``. An episode can carry an
explicit, reasoned exception:

    "style_exceptions": [{"rule": "runtime", "reason": "User asked for a 30 s special."}]

The lock also writes a generated block into ``<channel>/AGENTS.md`` so any
assistant reads the rules before starting. Hand-written text outside the
markers is kept.

    python -m studio.stylelock workspace/<slug>/channel --init        # starter lock from the channel
    python -m studio.stylelock workspace/<slug>/channel               # validate the lock, refresh AGENTS.md
    python -m studio.stylelock workspace/<slug>/channel --change "Allow music beds"  # after editing: bump version + changelog
    python -m studio.stylelock workspace/<slug>/channel --check       # audit every episode of the channel
"""

import argparse
from datetime import date
import json
from pathlib import Path

LOCK_NAME = "style-lock.json"
START, END = "<!-- style-lock:start (generated by studio.stylelock; edit style-lock.json, not this block) -->", "<!-- style-lock:end -->"
RULES = ("cast", "forbidden_paths", "dialogue", "runtime", "format", "grades", "music", "scale", "sounds")


def lock_path(channel_dir):
    return Path(channel_dir) / LOCK_NAME


def load_lock(channel_dir):
    path = lock_path(channel_dir)
    if not path.is_file():
        return None
    from .core import validate

    return validate(json.loads(path.read_text(encoding="utf-8")), "style_lock", LOCK_NAME)


# ------------------------------------------------------------------ checks

def _uses(episode):
    for scene in episode.get("scenes", []):
        for shot in scene.get("shots", []):
            yield shot, [layer for layer in shot.get("layers", []) if layer.get("kind") == "use"]


def _files(value):
    if isinstance(value, dict):
        for key, item in value.items():
            if key in {"file", "morph_to", "mask", "font"} and isinstance(item, str):
                yield item
            else:
                yield from _files(item)
    elif isinstance(value, list):
        for item in value:
            yield from _files(item)


def check(episode, lock, channel=None):
    """Violations of the lock by one source episode: [{"rule", "where", "message"}]."""
    found = []

    def add(rule, where, message):
        found.append({"rule": rule, "where": where, "message": message})

    cast = lock.get("cast") or {}
    allowed_rigs = set(cast.get("rigs", [])) | set(cast.get("props", []))
    if allowed_rigs:
        for shot, uses in _uses(episode):
            for layer in uses:
                if layer.get("ref") not in allowed_rigs:
                    add("cast", f"{shot['id']}/{layer['id']}",
                        f"uses rig '{layer.get('ref')}', which is not in the locked cast ({', '.join(sorted(allowed_rigs))})")
    for pattern in lock.get("forbidden_paths", []):
        for path in sorted(set(_files(episode))):
            if pattern in path:
                add("forbidden_paths", path, f"path contains '{pattern}', which the lock forbids")
    dialogue = lock.get("dialogue")
    if dialogue is not None:
        speakers = set(dialogue.get("speakers", []))
        for scene in episode.get("scenes", []):
            for shot in scene.get("shots", []):
                for line in shot.get("speech", []):
                    if not dialogue.get("allowed", False):
                        add("dialogue", shot["id"], f"speech line for '{line.get('speaker')}' but this channel has no dialogue")
                    elif speakers and line.get("speaker") not in speakers:
                        add("dialogue", shot["id"], f"speaker '{line.get('speaker')}' is not a locked voice ({', '.join(sorted(speakers))})")
    runtime = lock.get("runtime")
    if runtime:
        total = sum(float(shot["duration"]) for scene in episode.get("scenes", []) for shot in scene.get("shots", []))
        low, high = runtime.get("min", 0), runtime.get("max", 1e9)
        if not low - 1e-6 <= total <= high + 1e-6:
            add("runtime", "episode", f"runs {total:.2f} s; the lock allows {low:g}-{high:g} s")
    fmt = lock.get("format")
    if fmt:
        for key in ("width", "height", "fps"):
            if key in fmt and episode.get(key) != fmt[key]:
                add("format", "episode", f"{key} is {episode.get(key)}; the lock requires {fmt[key]}")
    grades = lock.get("grades")
    if grades is not None:
        posts = [("episode", episode.get("post") or {})] + [
            (shot["id"], shot.get("post") or {}) for scene in episode.get("scenes", []) for shot in scene.get("shots", [])]
        for where, post in posts:
            if post.get("grade") and post["grade"] not in grades:
                add("grades", where, f"grade '{post['grade']}' is not one of the locked grades ({', '.join(grades) or 'none'})")
            if post.get("lut") and "lut" not in grades:
                add("grades", where, "a custom LUT is not allowed by the lock")
    music = lock.get("music")
    if music is not None and not music.get("allowed", True) and episode.get("music"):
        add("music", "episode", "has a music bed; the lock says this channel has no music")
    tolerance = cast.get("scale_tolerance")
    if tolerance is not None and cast.get("rigs"):
        for shot, uses in _uses(episode):
            members = [layer for layer in uses if layer.get("ref") in cast["rigs"]]
            scales = [abs(float(layer.get("scale", 1))) for layer in members]
            if len(scales) >= 2 and max(scales) > min(scales) * (1 + tolerance):
                add("scale", shot["id"], "cast members share the frame at different scales "
                    f"({', '.join(f'{m['ref']} {s:g}' for m, s in zip(members, scales))}); keep the approved relative sizes")
    sounds = lock.get("sounds") or {}
    if channel is not None and sounds.get("library") and channel.get("audio_library") != sounds["library"]:
        add("sounds", "channel", f"channel audio_library is {channel.get('audio_library')}; the lock requires {sounds['library']}")
    return found


def review(episode, lock, channel=None):
    """Split violations into blocking ones and ones the episode excepts with a reason."""
    excepted = {item["rule"]: item["reason"] for item in episode.get("style_exceptions", [])}
    blocking, allowed = [], []
    for item in check(episode, lock, channel):
        if item["rule"] in excepted:
            allowed.append({**item, "reason": excepted[item["rule"]]})
        else:
            blocking.append(item)
    return blocking, allowed


def exemption(lock, episode_path):
    """The lock's exemption entry for an episode folder, if any."""
    if episode_path is None:
        return None
    name = Path(episode_path).resolve().parent.name
    return next((item for item in lock.get("exempt", []) if item["episode"] == name), None)


def enforce(episode, channel, channel_dir, episode_path=None):
    """Raise on blocking violations when the channel's lock is enforced. Returns a short report or None."""
    lock = load_lock(channel_dir)
    if lock is None:
        return None
    if exempt := exemption(lock, episode_path):
        return {"version": lock.get("version", 1), "exempt": exempt["reason"]}
    blocking, allowed = review(episode, lock, channel)
    if blocking and lock.get("enforce", True):
        lines = "\n".join(f"  - [{item['rule']}] {item['where']}: {item['message']}" for item in blocking)
        raise ValueError(
            f"Style lock v{lock.get('version', 1)} ({lock_path(channel_dir)}) rejects this episode:\n{lines}\n"
            "Fix the episode to match the channel. If the user approved a one-off, add "
            '"style_exceptions": [{"rule": ..., "reason": ...}] to the episode. If the user changed the channel\'s '
            "direction, edit style-lock.json and run `make style-lock CHANGE=\"...\"`.")
    return {"version": lock.get("version", 1), "violations": blocking, "excepted": allowed}


# ------------------------------------------------------------------ AGENTS.md

def render_rules(lock):
    cast = lock.get("cast") or {}
    lines = [START, "", f"## Style lock v{lock.get('version', 1)} (updated {lock.get('updated', '?')})", ""]
    if lock.get("summary"):
        lines += [lock["summary"], ""]
    lines += ["The studio enforces this lock: `validate` and `render` refuse episodes that break it. "
              "Change the look only when the user asks: edit `style-lock.json`, then run "
              "`make style-lock CHANNEL=<this channel.json> CHANGE=\"what changed and why\"`.", ""]
    if cast.get("rigs"):
        lines += ["### Cast", "", "| Rig | Notes |", "| --- | --- |"]
        notes = cast.get("notes", {})
        for rig in cast["rigs"]:
            lines.append(f"| `{rig}` | {notes.get(rig, '')} |")
        lines.append("")
        if cast.get("source"):
            lines += [f"Rig source: `{cast['source']}`. Rebuild rigs from it; never replace the cast with generated characters.", ""]
        if cast.get("scale_tolerance") is not None:
            lines += [f"Cast members in the same frame keep the same scale (tolerance {cast['scale_tolerance']:.0%}).", ""]
    facts = []
    dialogue = lock.get("dialogue")
    if dialogue is not None:
        facts.append("Dialogue: " + ("allowed for " + ", ".join(dialogue.get("speakers", [])) if dialogue.get("allowed")
                                    else "none. Characters make nonverbal sounds only."))
    if lock.get("runtime"):
        facts.append(f"Runtime: {lock['runtime'].get('min', 0):g}-{lock['runtime'].get('max', 0):g} s.")
    if lock.get("format"):
        f = lock["format"]
        facts.append("Format: " + " × ".join(str(f[k]) for k in ("width", "height") if k in f)
                     + (f" at {f['fps']} fps" if "fps" in f else "") + ".")
    if lock.get("grades") is not None:
        facts.append("Grades: " + (", ".join(f"`{g}`" for g in lock["grades"]) or "none") + ".")
    if lock.get("music") is not None:
        facts.append("Music: " + ("allowed." if lock["music"].get("allowed", True) else "none; ambience and Foley only."))
    sounds = lock.get("sounds") or {}
    if sounds.get("library"):
        facts.append(f"Sound library: `{sounds['library']}`" + (f" ({sounds['notes']})" if sounds.get("notes") else "") + ".")
    if lock.get("renderer"):
        facts.append(f"Renderer: `{lock['renderer']}`.")
    if facts:
        lines += ["### Locked settings", ""] + [f"- {fact}" for fact in facts] + [""]
    for title, key in (("### Rules", "rules"), ("### Never", "never")):
        if lock.get(key):
            lines += [title, ""] + [f"- {item}" for item in lock[key]] + [""]
    if lock.get("forbidden_paths"):
        lines += ["Forbidden asset paths: " + ", ".join(f"`{p}`" for p in lock["forbidden_paths"]) + ".", ""]
    if lock.get("exempt"):
        lines += ["Exempt (made before this lock, never copy their look blindly): "
                  + ", ".join(f"`{item['episode']}`" for item in lock["exempt"]) + ".", ""]
    if lock.get("references"):
        lines += ["### Approved references", "", "Match these before inventing anything new.", ""]
        for ref in lock["references"]:
            lines.append(f"- `{ref['path']}`: {ref.get('why', '')}")
        lines.append("")
    if lock.get("changelog"):
        lines += ["### Changelog", ""]
        for entry in reversed(lock["changelog"]):
            lines.append(f"- v{entry['version']} ({entry['date']}): {entry['change']}")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def write_agents(channel_dir, lock):
    path = Path(channel_dir) / "AGENTS.md"
    block = render_rules(lock)
    if path.is_file():
        text = path.read_text(encoding="utf-8")
        if START in text and END in text:
            head, rest = text.split(START, 1)
            text = head + block + rest.split(END, 1)[1]
        else:
            text = text.rstrip() + "\n\n" + block + "\n"
    else:
        text = ("# Channel rules\n\nRead this before planning or making anything for this channel. "
                "Channel memory lives in `../MEMORY.md`.\n\n" + block + "\n")
    path.write_text(text, encoding="utf-8")
    return path


# ------------------------------------------------------------------ commands

def starter(channel, channel_dir):
    """A conservative first lock from what the channel already has."""
    from .rigs import load_rigs

    rigs = sorted(load_rigs(channel, channel_dir) or {})
    lock = {"version": 1, "updated": date.today().isoformat(), "enforce": True,
            "summary": f"{channel.get('name', 'This channel')}: describe the approved look in one paragraph.",
            "cast": {"rigs": rigs, "notes": {rig: "" for rig in rigs}, "scale_tolerance": 0.1},
            "format": {"width": 1080, "height": 1920, "fps": 24},
            "rules": [], "never": ["Replace the approved cast with newly generated characters."],
            "references": [],
            "changelog": [{"version": 1, "date": date.today().isoformat(), "change": "Lock created from the channel."}]}
    if channel.get("audio_library"):
        lock["sounds"] = {"library": channel["audio_library"]}
    return lock


def save(channel_dir, lock):
    from .core import validate

    validate(lock, "style_lock", LOCK_NAME)
    lock_path(channel_dir).write_text(json.dumps(lock, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def bump(lock, change):
    version = int(lock.get("version", 1)) + 1
    today = date.today().isoformat()
    lock["version"], lock["updated"] = version, today
    lock.setdefault("changelog", []).append({"version": version, "date": today, "change": change})
    return lock


def audit(channel, channel_dir, lock):
    """Check every episode of the channel's workspace against the lock."""
    from .core import load

    episodes_dir = Path(channel_dir).parent / "episodes"
    report = []
    for path in sorted(episodes_dir.glob("*/episode.json")):
        try:
            episode = load(path, "episode")
        except ValueError as error:
            report.append({"episode": str(path), "error": str(error).splitlines()[0]})
            continue
        if exempt := exemption(lock, path):
            report.append({"episode": str(path), "ok": True, "exempt": exempt["reason"]})
            continue
        blocking, allowed = review(episode, lock, channel)
        report.append({"episode": str(path), "ok": not blocking, "violations": blocking, "excepted": allowed})
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("channel", type=Path, help="channel folder (holds channel.json)")
    parser.add_argument("--init", action="store_true", help="write a starter style-lock.json when missing")
    parser.add_argument("--change", help="record an approved change: bump the version and add a changelog entry")
    parser.add_argument("--check", action="store_true", help="audit every episode of the channel against the lock")
    args = parser.parse_args(argv)
    from .core import load

    channel_dir = args.channel if args.channel.is_dir() else args.channel.parent
    channel = load(channel_dir / "channel.json", "channel")
    try:
        lock = load_lock(channel_dir)
        if lock is None:
            if not args.init:
                print(f"studio: no {LOCK_NAME} in {channel_dir}. Run with --init to create one.")
                return 1
            lock = starter(channel, channel_dir)
            save(channel_dir, lock)
        if args.change:
            save(channel_dir, bump(lock, args.change))
        agents = write_agents(channel_dir, lock)
        result = {"lock": str(lock_path(channel_dir)), "version": lock["version"], "agents": str(agents)}
        if args.check:
            result["episodes"] = audit(channel, channel_dir, lock)
        print(json.dumps(result, indent=2, ensure_ascii=False))
        return 1 if args.check and any(not item.get("ok", False) for item in result["episodes"]) else 0
    except ValueError as error:
        print(f"studio: {error}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
